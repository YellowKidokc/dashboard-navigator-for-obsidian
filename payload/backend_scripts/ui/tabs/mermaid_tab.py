    def _browse_folder(self):
        path = QFileDialog.getExistingDirectory(self, "Select Papers Folder")
        if path:
            self.folder_edit.setText(path)
    
    def _start_scan(self):
        folder = self.folder_edit.text().strip()
        if not folder or not Path(folder).exists():
            QMessageBox.warning(self, "Invalid Folder", "Please select a valid folder.")
            return
        
        # Clear previous results
        self.results_table.setRowCount(0)
        self._results = []
        
        # UI state
        self.scan_btn.setEnabled(False)
        self.stop_btn.setEnabled(True)
        self.progress_bar.setVisible(True)
        self.progress_bar.setRange(0, 100)
        
        # Start worker
        self.worker = MermaidWorker(
            self.mermaid_engine,
            folder,
            inject_inline=self.inject_check.isChecked(),
            export_png=self.png_check.isChecked()
        )
        self.worker.progress.connect(self._on_progress)
        self.worker.file_done.connect(self._on_file_done)
        self.worker.finished.connect(self._on_finished)
        self.worker.start()
    
    def _stop_scan(self):
        if self.worker:
            self.worker.stop()
            self.status_label.setText("Stopping...")
    
    def _on_progress(self, current: int, total: int, filename: str):
        percent = int((current / total) * 100) if total > 0 else 0
        self.progress_bar.setValue(percent)
        self.status_label.setText(f"Processing {current}/{total}: {filename}")
    
    def _on_file_done(self, filename: str, success: bool, message: str):
        row = self.results_table.rowCount()
        self.results_table.insertRow(row)
        
        self.results_table.setItem(row, 0, QTableWidgetItem(filename))
        
        status = "✅" if success else "⚠️"
        status_item = QTableWidgetItem(status)
        status_item.setTextAlignment(Qt.AlignCenter)
        self.results_table.setItem(row, 1, status_item)
        
        self.results_table.setItem(row, 2, QTableWidgetItem(message))
        
        # Scroll to bottom
        self.results_table.scrollToBottom()
        
        self._results.append({'file': filename, 'success': success, 'message': message})
    
    def _on_finished(self, successful: int, total: int):
        self.scan_btn.setEnabled(True)
        self.stop_btn.setEnabled(False)
        self.progress_bar.setVisible(False)
        
        self.status_label.setText(f"Complete!")
        self.status_label.setStyleSheet("color: #00d9ff;")
        
        self.summary_label.setText(
            f"✅ {successful} papers with diagrams  |  "
            f"⚠️ {total - successful} skipped  |  "
            f"📊 {total} total scanned"
        )
        
        if successful > 0:
            QMessageBox.information(
                self,
                "Generation Complete",
                f"Generated mermaid diagrams for {successful} papers.\n\n"
                f"PNGs saved to: O:\\00_MEDIA\\Mermaid"
            )
    
    def _combine_all(self):
        """Combine all diagrams into one master graph."""
        folder = self.folder_edit.text().strip()
        if not folder or not Path(folder).exists():
            QMessageBox.warning(self, "Invalid Folder", "Please select a valid folder first.")
            return
        
        self.status_label.setText("Combining all diagrams...")
        
        try:
            # Collect all tags from all files
            all_tags = []
            folder_path = Path(folder)
            
            for md_file in folder_path.rglob("*.md"):
                tags = self.mermaid_engine.extract_tags(md_file)
                all_tags.extend(tags)
            
            if not all_tags:
                QMessageBox.warning(self, "No Tags", "No semantic tags found in any papers.")
                return
            
            # Generate master mermaid
            title = "THEOPHYSICS MASTER - All Dependencies"
            mermaid_code = self.mermaid_engine.generate_mermaid_code(all_tags, title)
            inline = self.mermaid_engine.generate_inline_mermaid(all_tags, title)
            
            # Export master PNG
            output_name = f"MASTER_COMBINED_{datetime.now().strftime('%Y%m%d_%H%M%S')}"
            png_path = self.mermaid_engine.export_to_png(mermaid_code, output_name)
            
            # Save master mermaid file
            master_md = Path(r"O:\00_MEDIA\Mermaid") / f"{output_name}.md"
            master_md.write_text(f"# {title}\n\n{inline}", encoding='utf-8')
            
            self.status_label.setText(f"Master diagram created: {output_name}")
            self.status_label.setStyleSheet("color: #00d9ff;")
            
            msg = f"Combined {len(all_tags)} tags from all papers.\n\n"
            if png_path:
                msg += f"PNG: {png_path}\n"
            msg += f"MD: {master_md}"
            
            QMessageBox.information(self, "Master Created", msg)
            
        except Exception as e:
            self.status_label.setText(f"Error: {e}")
            self.status_label.setStyleSheet("color: #e94560;")
            QMessageBox.critical(self, "Error", str(e))
    
    def _open_media_folder(self):
        media_path = Path(r"O:\00_MEDIA\Mermaid")
        media_path.mkdir(parents=True, exist_ok=True)
        os.startfile(str(media_path))
