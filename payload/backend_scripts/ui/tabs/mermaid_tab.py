        folder_layout = QVBoxLayout(folder_box)
        
        folder_row = QHBoxLayout()
        self.folder_edit = QLineEdit()
        self.folder_edit.setPlaceholderText("Select folder containing papers...")
        
        # Default to Logos Papers folder
