        btn_row.addWidget(self.scan_btn)
        
        self.combine_btn = QPushButton("🔗 Combine All to Master")
        self.combine_btn.clicked.connect(self._combine_all)
        self.combine_btn.setToolTip("Merge all diagrams into one master graph")
        btn_row.addWidget(self.combine_btn)
        
        self.stop_btn = QPushButton("⏹️ Stop")
