class MermaidWorker(QThread):
    """Background worker for mermaid generation."""
    progress = Signal(int, int, str)  # current, total, message
    file_done = Signal(str, bool, str)  # filename, success, message
    finished = Signal(int, int)  # successful, total
    
    def __init__(self, generator, folder_path: str, inject_inline: bool = True, export_png: bool = True):
        super().__init__()
        self.generator = generator
        self.folder_path = folder_path
        self.inject_inline = inject_inline
        self.export_png = export_png
        self._stop = False
    
    def stop(self):
        self._stop = True
    
    def run(self):
        folder = Path(self.folder_path)
        md_files = list(folder.rglob("*.md"))
        total = len(md_files)
        successful = 0
        
        for i, md_file in enumerate(md_files):
            if self._stop:
                break
            
            self.progress.emit(i + 1, total, md_file.name)
            
            try:
                # Extract tags
                tags = self.generator.extract_tags(md_file)
                
                if not tags:
                    self.file_done.emit(md_file.name, False, "No semantic tags")
                    continue
                
                # Generate mermaid code
                title = md_file.stem.replace('_', ' ')
                inline = self.generator.generate_inline_mermaid(tags, title)
                
                png_path = None
                if self.export_png:
                    mermaid_code = self.generator.generate_mermaid_code(tags, title)
                    png_path = self.generator.export_to_png(mermaid_code, md_file.stem)
                
                # Inject inline mermaid into the file
                if self.inject_inline and inline:
                    self._inject_mermaid_to_file(md_file, inline, png_path)
                
                successful += 1
                msg = f"{len(tags)} tags"
                if png_path:
                    msg += f" | PNG: {png_path.name}"
                self.file_done.emit(md_file.name, True, msg)
                
            except Exception as e:
                self.file_done.emit(md_file.name, False, str(e))
        
        self.finished.emit(successful, total)
    
    def _inject_mermaid_to_file(self, filepath: Path, inline: str, png_path: Optional[Path] = None):
        """Inject mermaid diagram before semantic mapping section."""
        content = filepath.read_text(encoding='utf-8', errors='ignore')
        
        # Build the section to inject
        section = "\n\n---\n\n## 🔗 Dependency Graph\n\n"
        if png_path and png_path.exists():
            section += f"📊 **[Full Size PNG]({png_path})**\n\n"
        section += inline + "\n"
        
        # Find injection point - before semantic tags or at end
        # Look for "## Semantic" or "%%tag::" or end of file
        
        # Check if already has dependency graph
        if "## 🔗 Dependency Graph" in content or "## Dependency Graph" in content:
            # Replace existing
            content = re.sub(
                r'## 🔗 Dependency Graph.*?(?=\n## |\n---\n\n## |\Z)',
                section.strip() + "\n",
                content,
                flags=re.DOTALL
            )
        else:
            # Find best insertion point
            patterns = [
                r'## Semantic Mapping',
                r'%%tag::',
                r'\*Generated by',
                r'---\s*$'
            ]
            
            inserted = False
            for pattern in patterns:
                match = re.search(pattern, content)
                if match:
                    pos = match.start()
                    content = content[:pos] + section + content[pos:]
                    inserted = True
                    break
            
            if not inserted:
                content += section
        
        filepath.write_text(content, encoding='utf-8')


class MermaidTab(QWidget):
    """Mermaid Generator Tab - scans papers and generates dependency graphs."""
    
    def __init__(self, settings_mgr, mermaid_engine):
        super().__init__()
        self.settings_mgr = settings_mgr
        self.mermaid_engine = mermaid_engine
        self.worker = None
        self._results = []
        
        self._init_ui()
    
    def _init_ui(self):
        layout = QVBoxLayout(self)
        layout.setContentsMargins(24, 24, 24, 24)
        layout.setSpacing(16)
        
        # Header
        header = QLabel("🎨 Mermaid Dependency Graphs")
        header.setStyleSheet("font-size: 20px; font-weight: bold; color: #00d9ff;")
        layout.addWidget(header)
        
        desc = QLabel("Scans papers for semantic tags (%%tag::...) and generates visual dependency graphs.")
        desc.setStyleSheet("color: #888; margin-bottom: 8px;")
        layout.addWidget(desc)
        
        # === FOLDER SELECTION ===
