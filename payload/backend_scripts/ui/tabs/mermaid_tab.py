        if Path(default_path).exists():
            self.folder_edit.setText(default_path)
        
        browse_btn = QPushButton("Browse")
        browse_btn.clicked.connect(self._browse_folder)
        
        folder_row.addWidget(self.folder_edit, 1)
        folder_row.addWidget(browse_btn)
        folder_layout.addLayout(folder_row)
        
        layout.addWidget(folder_box)
        
        # === OPTIONS ===
        options_box = QGroupBox("⚙️ Options")
        options_layout = QHBoxLayout(options_box)
        
        self.inject_check = QCheckBox("Inject inline mermaid into papers")
        self.inject_check.setChecked(True)
        self.inject_check.setToolTip("Add mermaid diagram before semantic mapping section")
        options_layout.addWidget(self.inject_check)
        
        self.png_check = QCheckBox("Export large PNG to O:\\00_MEDIA\\Mermaid")
        self.png_check.setChecked(True)
        self.png_check.setToolTip("Export high-resolution PNG for each paper")
        options_layout.addWidget(self.png_check)
        
        self.recursive_check = QCheckBox("Include subfolders")
